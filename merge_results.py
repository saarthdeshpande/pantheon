#!/usr/bin/env python
"""Merge Pantheon test data dirs into one; optionally analyse, export a CSV and
plot together with Pantheon's published results.

Usage:
  merge_results.py DIR [DIR ...] --out OUT [--published [PERF_JSON_OR_URL]]

Without --published only merges raw run logs and metadata (all DIRs must have
been run with the same link settings). With --published it additionally runs
src/analysis/plot.py on OUT (standard Pantheon plots + pantheon_perf.json),
then writes OUT/summary.csv and OUT/scatter_with_published.{pdf,svg,png}
(+ _mean). Schemes with no valid local runs are drawn from the published
perf.json as hollow markers, labelled "(published)". Run with python2.
"""

import argparse
import csv
import json
import os
import shutil
import subprocess
import sys
from os import path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import yaml

ROOT = path.dirname(path.abspath(__file__))
# https://pantheon.stanford.edu/measurements/emu/ (scenario 17: same link)
DEFAULT_PUBLISHED = ('https://s3.amazonaws.com/stanford-pantheon/emulation/'
                     'reports/2020-04-16T09-02-emu-17-pantheon-perf.json')
Y_RANGE = (0, 12.5636)  # y axis of the published Pantheon graph
SAME_KEYS = ('runtime', 'run_times', 'flows', 'uplink_trace', 'downlink_trace',
             'prepend_mm_cmds', 'extra_mm_link_args')
STATS_MARK = '# Below is generated by plot.py'

PUBLISHED_NAMES = {
    'indigo_musesc3': 'Indigo-MusesC3', 'indigo_musesc5': 'Indigo-MusesC5',
    'indigo_musesd': 'Indigo-MusesD', 'indigo_musest': 'Indigo-MusesT',
    'muses_dtree': 'Muses_DecisionTree',
    'muses_dtreeh0': 'Muses_DecisionTreeH0',
    'muses_dtreer0': 'Muses_DecisionTreeR0', 'quic': 'QUIC Cubic',
    'vegas': 'TCP Vegas', 'verus': 'Verus', 'webrtc': 'WebRTC media',
}
PUB_MARKERS = ['o', 's', '^', 'v', 'D', 'P', 'X', '*', 'h', 'p', '<']


def merge(dirs, out):
    if path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)

    meta = None
    schemes = []
    for d in dirs:
        m = json.load(open(path.join(d, 'pantheon_metadata.json')))
        if meta is None:
            meta = m
        for k in SAME_KEYS:
            if m.get(k) != meta.get(k):
                sys.exit('%s differs between inputs: %r vs %r (%s)'
                         % (k, meta.get(k), m.get(k), d))
        schemes += m['cc_schemes']
        for f in os.listdir(d):
            # raw per-run logs only; analysis outputs are regenerated
            if '_run' not in f or f.startswith('pantheon_') or \
                    f.endswith(('.png', '.pdf')):
                continue
            if '_stats_run' in f:  # drop output of an earlier plot.py run
                text = open(path.join(d, f)).read().split(STATS_MARK)[0]
                open(path.join(out, f), 'w').write(text.rstrip('\n') + '\n')
            else:
                shutil.copy(path.join(d, f), out)
    meta['cc_schemes'] = schemes
    json.dump(meta, open(path.join(out, 'pantheon_metadata.json'), 'w'),
              indent=4)
    return schemes


def load_json(src):
    if src.startswith(('http://', 'https://')):
        try:
            from urllib2 import urlopen  # python2
        except ImportError:
            from urllib.request import urlopen
        return json.loads(urlopen(src).read().decode('utf-8'))
    return json.load(open(src))


def points(perf, scheme):
    """(delay ms, throughput Mbit/s, loss fraction, run id) per run."""
    runs = perf.get(scheme, {})
    return [(r['all']['delay'], r['all']['tput'], r['all']['loss'], rid)
            for rid, r in sorted(runs.items()) if 'all' in r]


def summarize(out, published, config):
    local = json.load(open(path.join(out, 'pantheon_perf.json')))

    rows = []  # source, scheme, name, run, tput, delay, loss_pct
    for cc in sorted(local):
        for delay, tput, loss, rid in points(local, cc):
            rows.append(('local', cc, config[cc]['name'], rid, tput, delay,
                         None if loss is None else loss * 100))
    local_ok = set(r[1] for r in rows)
    for cc in sorted(published):
        if cc in local_ok:
            continue
        for delay, tput, loss, rid in points(published, cc):
            rows.append(('published', cc, PUBLISHED_NAMES.get(cc, cc), rid,
                         tput, delay, None if loss is None else loss * 100))

    with open(path.join(out, 'summary.csv'), 'w') as fh:
        w = csv.writer(fh)
        w.writerow(['source', 'scheme', 'name', 'run', 'throughput_mbps',
                    'delay_p95_ms', 'loss_pct'])
        w.writerows(rows)

    fig_raw, ax_raw = plt.subplots()
    fig_mean, ax_mean = plt.subplots()
    cmap = plt.get_cmap('tab20')
    xs, pub_i = [], 0
    for cc in sorted(set(r[1] for r in rows),
                     key=lambda c: [r[2] for r in rows if r[1] == c][0]):
        mine = [r for r in rows if r[1] == cc]
        x, y = [r[5] for r in mine], [r[4] for r in mine]
        xs += x
        name = mine[0][2]
        if mine[0][0] == 'local':
            kw = dict(color=config[cc]['color'], marker=config[cc]['marker'])
            label = name
        else:
            kw = dict(facecolors='none', edgecolors=cmap(pub_i % 20),
                      marker=PUB_MARKERS[pub_i % len(PUB_MARKERS)])
            label = '%s (published)' % name
            pub_i += 1
        ax_raw.scatter(x, y, label=label, clip_on=False, **kw)
        ax_mean.scatter(np.mean(x), np.mean(y), clip_on=False, **kw)
        ax_mean.annotate(label, (np.mean(x), np.mean(y)), fontsize=7)

    for ax in (ax_raw, ax_mean):
        ax.set_xlim(max(xs) * 1.02, min(xs) * 0.98)  # delay axis reversed
        ax.set_ylim(*Y_RANGE)
        ax.set_xlabel('95th percentile one-way delay (ms)', fontsize=12)
        ax.set_ylabel('Average throughput (Mbit/s)', fontsize=12)
        ax.grid()
    ax_raw.set_title('local runs (filled) + published (hollow)', fontsize=9,
                     y=1.02)
    lgd = ax_raw.legend(scatterpoints=1, bbox_to_anchor=(1, 0.5),
                        loc='center left', fontsize=8)
    prefix = path.join(out, 'scatter_with_published')
    for ext in ('pdf', 'svg', 'png'):
        fig_raw.savefig('%s.%s' % (prefix, ext), dpi=200,
                        bbox_extra_artists=(lgd,), bbox_inches='tight')
        fig_mean.savefig('%s_mean.%s' % (prefix, ext), dpi=200,
                         bbox_inches='tight')

    for cc in json.load(open(path.join(out, 'pantheon_metadata.json')))[
            'cc_schemes']:
        if cc not in local_ok:
            sys.stderr.write('note: %s has no valid local runs%s\n' % (
                cc, '' if cc in published else ' and no published data'))


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    p.add_argument('dirs', nargs='+', metavar='DIR',
                   help='Pantheon data dirs (test.py --data-dir)')
    p.add_argument('--out', required=True, help='merged output dir')
    p.add_argument('--published', nargs='?', const=DEFAULT_PUBLISHED,
                   metavar='PERF_JSON_OR_URL',
                   help='analyse OUT, write summary.csv and a scatter that '
                   'adds published results (default: Pantheon emu-17)')
    args = p.parse_args()

    merge(args.dirs, args.out)
    if args.published is None:
        return

    published = load_json(args.published)
    config = yaml.safe_load(open(path.join(ROOT, 'src', 'config.yml')))[
        'schemes']
    subprocess.check_call([sys.executable,
                           path.join(ROOT, 'src', 'analysis', 'plot.py'),
                           '--data-dir', args.out])
    summarize(args.out, published, config)


if __name__ == '__main__':
    main()
